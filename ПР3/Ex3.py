


print("--- Проверка прохождения кирпича в отверстие ---")

try:
    # Ввод размеров кирпича
    a = float(input("Введите сторону кирпича a: "))
    b = float(input("Введите сторону кирпича b: "))
    c = float(input("Введите сторону кирпича c: "))
    
    # Ввод размеров отверстия
    r = float(input("Введите сторону отверстия r: "))
    s = float(input("Введите сторону отверстия s: "))

    # Проверка данных
    if a <= 0 or b <= 0 or c <= 0 or r <= 0 or s <= 0:
        print("Ошибка: Размеры должны быть больше нуля!")
    else:
        # Проверяем все возможные варианты прохождения
        option1 = (a <= r and b <= s) or (a <= s and b <= r)
        option2 = (a <= r and c <= s) or (a <= s and c <= r)
        option3 = (b <= r and c <= s) or (b <= s and c <= r)

        # Если хотя бы один вариант подошел
        if option1 or option2 or option3:
            print("Ответ: Кирпич ПРОЙДЕТ сквозь отверстие.")
        else:
            print("Ответ: Кирпич НЕ ПРОЙДЕТ сквозь отверстие.")

except ValueError:
    print("Ошибка: Вводите только числа.")


input()
